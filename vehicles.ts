export interface EffectiveVehicleStats {
  driveForce: number;
  maxSpeed: number;
  springK: number;
  damperC: number;
  tireGrip: number;
  fuelCapacity: number;
  airPitchTorque: number;
}

export function getEffectiveStats(spec: VehicleSpec, levels: UpgradeLevels): EffectiveVehicleStats {
  const eng = levels.engine - 1;
  const sus = levels.suspension - 1;
  const tir = levels.tires - 1;
  const fue = levels.fuel - 1;

  return {
    driveForce: spec.driveForce * (1 + eng * 0.115),
    maxSpeed: spec.maxSpeed * (1 + eng * 0.08),
    springK: spec.springK * (1 + sus * 0.065),
    damperC: spec.damperC * (1 + sus * 0.085),
    tireGrip: spec.tireGrip * (1 + tir * 0.095),
    fuelCapacity: spec.fuelCapacity * (1 + fue * 0.16),
    airPitchTorque: spec.airPitchTorque * (1 + sus * 0.04),
  };
}

